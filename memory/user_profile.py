class UserProfile:

    def __init__(self):

        self.resume = None

        self.ats = None

        self.career = None

        self.interview = None

    def set_resume(self, resume):

        self.resume = resume

    def set_ats(self, ats):

        self.ats = ats

    def set_career(self, career):

        self.career = career

    def set_interview(self, interview):

        self.interview = interview